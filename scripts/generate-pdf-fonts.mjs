import fs from 'node:fs';

const files = {
  regular: 'LiberationSans-Regular.ttf',
  bold: 'LiberationSans-Bold.ttf',
  italic: 'LiberationSans-Italic.ttf',
  boldItalic: 'LiberationSans-BoldItalic.ttf',
};

let out = '// Generated by scripts/generate-pdf-fonts.mjs. Do not edit by hand.\n';
for (const [key, file] of Object.entries(files)) {
  const base64 = fs.readFileSync('src/assets/fonts/' + file).toString('base64');
  out += 'export const ' + key + 'Base64 = ' + JSON.stringify(base64) + ';\n';
}
out += '\nexport const pdfFontNames = {\n';
out += '  regular: "LiberationSans-Regular.ttf",\n';
out += '  bold: "LiberationSans-Bold.ttf",\n';
out += '  italic: "LiberationSans-Italic.ttf",\n';
out += '  boldItalic: "LiberationSans-BoldItalic.ttf",\n';
out += '} as const;\n';

fs.writeFileSync('src/services/export/pdfFontData.ts', out);